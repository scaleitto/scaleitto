// Shared by scripts/migrate.mjs (manual run) and src/instrumentation.ts (automatic run at server start).
// Takes an open mysql2/promise connection so it has no dependencies of its own.
import { readFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import path from "node:path";

// -1 = unlimited
const defaultPlans = [
  {
    code: "starter",
    name: "Starter",
    priceMonthly: 0,
    limits: { maxProducts: 20, maxOrdersPerMonth: 100, maxStaff: 1, maxLandingPages: 2, maxAiPerMonth: 3 },
    features: ["landing_pages", "variants", "pixels"],
  },
  {
    code: "pro",
    name: "Pro",
    priceMonthly: 3900,
    limits: { maxProducts: 200, maxOrdersPerMonth: 2000, maxStaff: 5, maxLandingPages: 50, maxAiPerMonth: 50 },
    features: ["landing_pages", "variants", "pixels", "custom_domain", "google_sheets", "abandoned_cart", "upsell", "delivery_integrations", "analytics"],
  },
  {
    code: "business",
    name: "Business",
    priceMonthly: 9900,
    limits: { maxProducts: -1, maxOrdersPerMonth: -1, maxStaff: 20, maxLandingPages: -1, maxAiPerMonth: 300 },
    features: ["landing_pages", "variants", "pixels", "custom_domain", "google_sheets", "abandoned_cart", "upsell", "delivery_integrations", "analytics", "ai", "api"],
  },
];

// Applies the SQL files generated by `drizzle-kit generate` (in journal order) and seeds default plans.
export async function runMigrations(connection, root, log = console.log) {
  // Several server processes can start at once on cPanel; only one may migrate.
  const [[{ locked }]] = await connection.query("SELECT GET_LOCK('scaleitto_migrate', 60) AS locked");
  if (locked !== 1) throw new Error("Could not get the migration lock");
  try {
    await connection.query(
      "CREATE TABLE IF NOT EXISTS _migrations (name VARCHAR(191) PRIMARY KEY, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)",
    );
    const journal = JSON.parse(readFileSync(path.join(root, "drizzle/meta/_journal.json"), "utf8"));
    const [doneRows] = await connection.query("SELECT name FROM _migrations");
    const done = new Set(doneRows.map((r) => r.name));
    for (const { tag } of journal.entries) {
      if (done.has(tag)) continue;
      const sqlText = readFileSync(path.join(root, "drizzle", `${tag}.sql`), "utf8");
      for (const statement of sqlText.split("--> statement-breakpoint")) {
        if (statement.trim()) await connection.query(statement);
      }
      await connection.query("INSERT INTO _migrations (name) VALUES (?)", [tag]);
      log(`✓ applied ${tag}`);
    }

    for (const p of defaultPlans) {
      const [rows] = await connection.query("SELECT id, limits FROM plans WHERE code = ?", [p.code]);
      if (rows.length > 0) {
        // Limits added in later versions get their default value; existing values are kept.
        const current = typeof rows[0].limits === "string" ? JSON.parse(rows[0].limits) : rows[0].limits;
        const missing = Object.keys(p.limits).filter((k) => !(k in current));
        if (missing.length) {
          const merged = { ...current };
          for (const k of missing) merged[k] = p.limits[k];
          await connection.query("UPDATE plans SET limits = ? WHERE id = ?", [JSON.stringify(merged), rows[0].id]);
          log(`✓ plan "${p.code}" got new limits: ${missing.join(", ")}`);
        }
      } else {
        await connection.query(
          "INSERT INTO plans (id, code, name, price_monthly, limits, features) VALUES (?, ?, ?, ?, ?, ?)",
          [randomUUID(), p.code, p.name, p.priceMonthly, JSON.stringify(p.limits), JSON.stringify(p.features)],
        );
        log(`✓ plan "${p.code}" created`);
      }
    }
  } finally {
    await connection.query("SELECT RELEASE_LOCK('scaleitto_migrate')");
  }
}
