// Applies pending SQL migrations from ./drizzle and seeds default plans.
// Usage: node scripts/migrate.mjs   (reads DATABASE_URL from the environment or .env)
import { readFileSync, existsSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";
import mysql from "mysql2/promise";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

if (!process.env.DATABASE_URL && existsSync(path.join(root, ".env"))) {
  for (const line of readFileSync(path.join(root, ".env"), "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Z_]+)\s*=\s*"?(.*?)"?\s*$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
  }
}

const connection = await mysql.createConnection({ uri: process.env.DATABASE_URL });

// Applies the SQL files generated by `drizzle-kit generate`, in journal order.
// Only depends on mysql2 so it also runs from the standalone production bundle.
await connection.query(
  "CREATE TABLE IF NOT EXISTS _migrations (name VARCHAR(191) PRIMARY KEY, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)",
);
const journal = JSON.parse(readFileSync(path.join(root, "drizzle/meta/_journal.json"), "utf8"));
const [doneRows] = await connection.query("SELECT name FROM _migrations");
const done = new Set(doneRows.map((r) => r.name));
for (const { tag } of journal.entries) {
  if (done.has(tag)) continue;
  const sqlText = readFileSync(path.join(root, "drizzle", `${tag}.sql`), "utf8");
  for (const statement of sqlText.split("--> statement-breakpoint")) {
    if (statement.trim()) await connection.query(statement);
  }
  await connection.query("INSERT INTO _migrations (name) VALUES (?)", [tag]);
  console.log(`✓ applied ${tag}`);
}

// -1 = unlimited
const defaultPlans = [
  {
    code: "starter",
    name: "Starter",
    priceMonthly: 0,
    limits: { maxProducts: 20, maxOrdersPerMonth: 100, maxStaff: 1, maxLandingPages: 2 },
    features: ["landing_pages", "variants", "pixels"],
  },
  {
    code: "pro",
    name: "Pro",
    priceMonthly: 3900,
    limits: { maxProducts: 200, maxOrdersPerMonth: 2000, maxStaff: 5, maxLandingPages: 50 },
    features: ["landing_pages", "variants", "pixels", "custom_domain", "google_sheets", "abandoned_cart", "upsell", "delivery_integrations", "analytics"],
  },
  {
    code: "business",
    name: "Business",
    priceMonthly: 9900,
    limits: { maxProducts: -1, maxOrdersPerMonth: -1, maxStaff: 20, maxLandingPages: -1 },
    features: ["landing_pages", "variants", "pixels", "custom_domain", "google_sheets", "abandoned_cart", "upsell", "delivery_integrations", "analytics", "ai", "api"],
  },
];

for (const p of defaultPlans) {
  const [rows] = await connection.query("SELECT id FROM plans WHERE code = ?", [p.code]);
  if (rows.length === 0) {
    await connection.query(
      "INSERT INTO plans (id, code, name, price_monthly, limits, features) VALUES (?, ?, ?, ?, ?, ?)",
      [randomUUID(), p.code, p.name, p.priceMonthly, JSON.stringify(p.limits), JSON.stringify(p.features)],
    );
    console.log(`✓ plan "${p.code}" created`);
  }
}

await connection.end();
